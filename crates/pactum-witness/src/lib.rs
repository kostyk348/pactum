//! # pactum-witness
//!
//! Нотариус контента: сервис, который фиксирует «в момент T этот документ
//! имел такой-то SHA-256» — подписью, которую можно проверить офлайн, и
//! журналом, который нельзя переписать задним числом.
//!
//! Задача старая (trusted timestamping), но Pactum решает её своими
//! примитивами, без денег и без доверия нотариусу на слово:
//!
//! * каждая запись — **приёмник** (receipt): хеш содержимого, номер, время,
//!   хеш предыдущей записи и подпись ECDSA P-256 (см. [`Receipt`]);
//! * записи образуют **цепочку** — переписать историю нельзя, не сломав
//!   `verify()` (см. [`Journal`]);
//! * приёмник **самодостаточен**: в нём лежит открытый ключ нотариуса, так
//!   что проверка не требует ни сервера, ни сети — только файл приёмника;
//! * **checkpoint** — подписанная голова цепочки, которую сервис по желанию
//!   публикует в хаб (`witness.head`): третьи стороны со-свидетельствуют,
//!   и задним числом переписать журнал уже нельзя, даже имея ключ диска;
//! * отказы честные: `413` — «слишком большое тело», `429` — «слишком
//!   часто», `404` — «такой документ не нотариован», ничего не молчит.
//!
//! Типовое применение: журналистика (фиксация страницы до публикации),
//! релизы (фиксация артефактов), договоры и документы, исследовательские
//! данные — везде, где «у меня был этот файл ещё тогда» нужно доказать.

