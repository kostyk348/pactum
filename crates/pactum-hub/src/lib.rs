//! # pactum-hub
//!
//! Хаб подписок — честная доставка событий вместо опроса.
//!
//! Порт `hubd` (kostyk348/hubd) в состав Pactum, универсализированный:
//! топик — что угодно. Изменение документа в архиве, событие контракта,
//! телеметрия устройства, отчёт CI, лента организации. Подписчик — тоже что
//! угодно: сервис, человек с локальным слушателем, устройство, агент.
//!
//! Честность — главная фича, унаследованная от hubd:
//!
//! * подписчик отвечает `404` — это вежливое «не хочу»: хаб снимает подписку
//!   и сообщает об этом (`hub.mode=denied`), а не молча бросает сообщения;
//! * доставка не прошла 8 раз — подписка честно помечается `degraded`,
//!   издателю при публикации возвращается `503` с перечнем;
//! * сообщение больше лимита — `413`, а не тихая потеря;
//! * очередь ретраев персистентна: перезапуск хаба её не теряет;
//! * подписки арендные: максимум [`MAX_LEASE_S`], продление — повторной
//!   подпиской.

